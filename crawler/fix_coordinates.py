def geocode(address):
    """国土地理院APIで住所→座標を取得"""
    url = "https://msearch.gsi.go.jp/address-search/AddressSearch"
    try:
        res = requests.get(url, params={"q": address}, timeout=10)
        res.raise_for_status()
        data = res.json()
        if data:
            lng, lat = data[0]["geometry"]["coordinates"]
            return round(lat, 6), round(lng, 6)
    except Exception as e:
        print(f"  エラー: {e}")
    return None, None

def main():
    print(f"全{len(SCHOOLS)}校の座標を更新します")
    success = 0
    failed = []

    for i, (school_id, address) in enumerate(SCHOOLS, 1):
        print(f"[{i}/{len(SCHOOLS)}] {address}", end=" → ")
        lat, lng = geocode(address)
        if lat and lng:
            supabase.table("schools").update({"lat": lat, "lng": lng}).eq("id", school_id).execute()
            print(f"({lat}, {lng}) ✅")
            success += 1
        else:
            print("取得失敗 ❌")
            failed.append(address)
        time.sleep(0.3)

    print(f"\n完了: {success}校成功 / {len(failed)}校失敗")
    if failed:
        print("失敗した住所:")
        for a in failed:
            print(f"  {a}")

if __name__ == "__main__":
    main()
